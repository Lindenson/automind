"""The contract table of the graph (spec 014 T106): per node its retry, what it reads, what it writes and where the
turn may go next, then per state key its writers — rendered from the `@node` declarations, the owners registry and
the compiled graph's edges. Committed as specs/014-node-contracts/contract.md; a test fails when it is stale."""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from typing import Any

from automind.chat.dialog.contract.models import required_reads
from automind.chat.dialog.contract.node import Node
from automind.chat.dialog.contract.owners import OWNERS, RESET_NODE

Edge = tuple[str, str, bool]  # source, target, conditional (chosen at run time)

_HEAD = """# Graph node contracts (spec 014)

Generated by `python -m automind.chat.dialog.contract` from the `@node` declarations, the owners registry
(`chat/dialog/contract/owners.py`) and the compiled graph; do not edit — a test fails when this file differs from the
code. Reads: `key!` is required (the node cannot run without it). Writes: `key!` is written on every branch. Next:
`?target` is chosen at run time (a router or a fan-out). `research_job` reads a `Send` payload (one job), not the
turn state. `load_case` also resets every per-turn key (`state.PER_TURN_RESET`).
"""


_NODES = "## Nodes\n\n| node | retry | reads | writes | next |\n|---|---|---|---|---|"
_OWNERS = "## Owners\n\n| key | writers | merge | one writer at |\n|---|---|---|---|"


def render(nodes: Sequence[Node[Any, Any]], edges: Iterable[Edge]) -> str:
    """The whole document: the node table, then the owners table."""
    nxt: dict[str, list[str]] = {}
    for source, target, conditional in sorted(edges):
        nxt.setdefault(source, []).append(("?" if conditional else "") + target)
    rows = [_node_row(n, nxt.get(n.name, [])) for n in nodes]
    owners = [_owner_row(key) for key in sorted(OWNERS)]
    return "\n".join([_HEAD, _NODES, *rows, "", _OWNERS, *owners, ""])


def _node_row(n: Node[Any, Any], targets: list[str]) -> str:
    required = required_reads(n.reads)
    reads = [f"{k}!" if k in required else k for k in n.reads.model_fields]
    always = n.writes.always_written()
    if n.name == RESET_NODE:
        writes = ["chat_id!", "turn_id!", "case_version!", "(every per-turn key)"]
    else:
        writes = [f"{k}!" if k in always else k for k in n.writes.model_fields]
    return f"| {n.name} | {n.retry} | {_cell(reads)} | {_cell(writes)} | {_cell(targets)} |"


def _owner_row(key: str) -> str:
    o = OWNERS[key]
    return f"| {key} | {_cell(sorted(o.writers))} | {o.merge} | {o.until or '—'} |"


def _cell(items: list[str]) -> str:
    return ", ".join(items) if items else "—"
